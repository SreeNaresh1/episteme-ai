#!/usr/bin/env node

/**
 * Episteme GitHub Action Runner
 * Verifies course links, documentation, and educational resources for paywalls & Schema.org data.
 */

import { execSync } from 'node:child_process';
import fs from 'node:fs';

const singleUrl = process.env.INPUT_URL || '';
const multiUrls = process.env.INPUT_URLS || '';
const failOnPaywall = (process.env.INPUT_FAIL_ON_PAYWALL || 'true').toLowerCase() === 'true';

// Extract all candidate URLs
const candidates = [
  ...singleUrl.split('\n'),
  ...multiUrls.split('\n'),
]
  .map((u) => u.trim())
  .filter((u) => u.length > 0 && /^https?:\/\//i.test(u));

if (candidates.length === 0) {
  console.log('::warning::No valid HTTP/HTTPS URLs provided to Episteme Action.');
  process.exit(0);
}

console.log(`\n🔍 Episteme Action: Auditing ${candidates.length} URL(s) for paywalls & free access...`);

const results = [];
let hasFailure = false;

for (const url of candidates) {
  console.log(`Checking: ${url}`);
  try {
    const raw = execSync(`npx --yes episteme-check@latest "${url}" --json`, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 30000,
    });
    const parsed = JSON.parse(raw.trim());
    results.push(parsed);
    if (!parsed.is_free) {
      hasFailure = true;
      console.log(`  ✗ Paywall or unverified free status: ${url}`);
    } else {
      console.log(`  ✓ Verified free: ${url}`);
    }
  } catch (err) {
    hasFailure = true;
    let parsedErr = {
      url,
      final_url: url,
      reachable: false,
      http_status: 0,
      is_free: false,
      error: 'Inspection timed out or failed to parse',
      confidence_score: 0,
      detected_free_markers: [],
      detected_paywall_markers: [],
      page_title: '',
      has_json_ld_schema: false,
      is_accessible_for_free_schema: false,
    };
    if (err.stdout) {
      try {
        parsedErr = JSON.parse(err.stdout.toString().trim());
      } catch {
        // Fallback
      }
    }
    results.push(parsedErr);
    console.log(`  ✗ Failed / Paywall detected: ${url}`);
  }
}

// 1. Build Step Summary Markdown Table
let summaryMarkdown = `## 🎓 Episteme Courseware & Paywall Verification Report\n\n`;
summaryMarkdown += `Audited **${results.length}** URL(s) using **Cheerio DOM Paywall Heuristics** and **Schema.org \`isAccessibleForFree\`** structured data.\n\n`;
summaryMarkdown += `| Resource URL | Status | Verdict | Schema.org | Confidence |\n`;
summaryMarkdown += `| :--- | :---: | :---: | :---: | :---: |\n`;

for (const r of results) {
  const title = r.page_title ? `**${r.page_title.slice(0, 40)}**<br>` : '';
  const cleanUrl = `<a href="${r.final_url || r.url}">${(r.final_url || r.url).replace(/^https?:\/\//, '').slice(0, 35)}...</a>`;
  const status = r.reachable ? `\`${r.http_status} OK\`` : `\`Unreachable\``;
  const verdict = r.is_free ? `✅ **Free**` : `❌ **Paywall / Paid**`;
  const schema = r.has_json_ld_schema
    ? (r.is_accessible_for_free_schema ? `\`isAccessibleForFree\`` : `\`Schema Present\``)
    : `\`None\``;
  const conf = `${Math.round(r.confidence_score * 100)}%`;

  summaryMarkdown += `| ${title}${cleanUrl} | ${status} | ${verdict} | ${schema} | ${conf} |\n`;
}

summaryMarkdown += `\n*Generated by [Episteme AI](https://github.com/SreeNaresh1/episteme-ai) & [episteme-check](https://www.npmjs.com/package/episteme-check)*\n`;

// Append to GITHUB_STEP_SUMMARY if present
if (process.env.GITHUB_STEP_SUMMARY) {
  try {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, summaryMarkdown);
    console.log('✓ Successfully wrote summary report to GITHUB_STEP_SUMMARY.');
  } catch (e) {
    console.error('Notice: Could not write to GITHUB_STEP_SUMMARY:', e.message);
  }
}

// Write to GITHUB_OUTPUT
if (process.env.GITHUB_OUTPUT) {
  try {
    fs.appendFileSync(process.env.GITHUB_OUTPUT, `all-free=${!hasFailure}\ntotal-checked=${results.length}\n`);
  } catch (e) {
    console.error('Notice: Could not write to GITHUB_OUTPUT:', e.message);
  }
}

console.log('\n--- Final Verification Summary ---');
console.log(`Total URLs Audited: ${results.length}`);
console.log(`Overall Status:     ${!hasFailure ? 'ALL PASSED (VERIFIED FREE)' : 'PAYWALLS / FAILURES DETECTED'}`);
console.log('----------------------------------\n');

if (hasFailure && failOnPaywall) {
  console.error('::error::Episteme verification failed: One or more URLs hit paywalls or are inaccessible.');
  process.exit(1);
}

process.exit(0);
